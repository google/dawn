import argparse
import json
import sys
import subprocess
from pathlib import Path

SCRIPT_DIR = Path(__file__).resolve().parent
DAWN_ROOT = SCRIPT_DIR.parent


def fail(message: str) -> None:
    print(message, file=sys.stderr)
    sys.exit(1)


def find_latest_findings_file() -> Path:
    # Look for clang-tidy-*-findings.json (generated by tools/run-tricium-clang-tidy.py)
    # in the current working directory.
    findings_files = sorted(Path.cwd().glob("clang-tidy-*-findings.json"))
    if not findings_files:
        fail(
            "Error: No clang-tidy-*-findings.json found in the current directory.\n"
            "Please run tools/run-tricium-clang-tidy.py first to generate findings, or specify --findings."
        )
    return findings_files[-1]


def main():
    if Path.cwd().resolve() != DAWN_ROOT.resolve():
        fail("Error: must be run from the Dawn root directory.")

    parser = argparse.ArgumentParser(
        description=
        "Extract files matching a given clang-tidy check from findings.json and apply autofixes."
        "Note findings.json is only used to determine which files to inspect - this script applies ALL fixes for that check in the file, regardless of the exact fixits listed in findings.json.",
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    # Build directory (Required positional argument to match tools/run-tricium-clang-tidy.py)
    parser.add_argument("outdir", help="The build directory, e.g., out/tidy")
    parser.add_argument(
        "-c",
        "--check",
        required=True,
        help=
        "The specific clang-tidy check to apply fixes for (e.g., bugprone-parent-virtual-call)."
    )
    parser.add_argument(
        "-f",
        "--findings",
        help=
        "Path to the findings JSON file. If not specified, the latest clang-tidy-*-findings.json file is used."
    )

    args = parser.parse_args()

    # Determine findings file path
    if args.findings:
        findings_path = Path(args.findings)
        if not findings_path.is_file():
            fail(f"Error: Findings file not found: {findings_path}")
    else:
        findings_path = find_latest_findings_file()

    print(f"Reading findings from: {findings_path}")

    # Parse findings JSON
    try:
        with open(findings_path, "r", encoding="utf-8") as f:
            data = json.load(f)
    except Exception as e:
        fail(f"Error parsing findings JSON file {findings_path}: {e}")

    # Extract matching files
    files_to_fix = set()
    diagnostics = data.get("diagnostics", [])
    for diag in diagnostics:
        if diag.get("diag_name") == args.check:
            file_path = diag.get("file_path")
            if file_path:
                files_to_fix.add(file_path)

    if not files_to_fix:
        print(f"No diagnostics found matching check: '{args.check}'")
        return

    print(
        f"Found {len(files_to_fix)} file(s) with diagnostics for '{args.check}':"
    )
    for file in sorted(files_to_fix):
        print(f"  {file}")

    # Locate clang-tidy binary
    if args.binary:
        clang_tidy_bin = Path(args.binary)
    else:
        clang_tidy_bin = Path(
            "third_party/llvm-build/Release+Asserts/bin/clang-tidy")
        if sys.platform == "win32":
            clang_tidy_bin = clang_tidy_bin.with_suffix(".exe")

    if not clang_tidy_bin.is_file():
        fail(f"Error: clang-tidy binary not found at: {clang_tidy_bin}")

    # Validate build directory
    outdir_path = Path(args.outdir)
    if not outdir_path.is_dir() or not (outdir_path /
                                        "compile_commands.json").is_file():
        fail(
            f"Error: Build directory '{args.outdir}' does not exist or lacks compile_commands.json."
        )

    # Assemble and run the command
    cmd = [
        str(clang_tidy_bin),
        f"-p={outdir_path}",
        f"-checks=-*,{args.check}",
        "--fix",
    ] + sorted(list(files_to_fix))

    print(f"\nRunning command:\n  {' '.join(cmd)}")
    try:
        subprocess.run(cmd, check=True)
        print("\nFixes successfully applied!")
    except subprocess.CalledProcessError as e:
        fail(f"\nClang-tidy failed with exit code {e.returncode}")


if __name__ == "__main__":
    main()
